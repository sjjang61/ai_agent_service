"""응답 범위 제한: 에이전트가 '마지막 사용자 메시지'가 요청한 것에만 답하도록 한다.

대화 기록을 실제 턴으로 다시 보여 주면 모델이 이전 요청(예: 주가 조회)을 새 메시지에도 이어서 수행하는 일이 있다.
특히 사용자가 "나는 테니스를 좋아해" 같은 서술만 했는데 직전의 조회를 다시 실행하고 결과를 또 보여 주는 문제가 있었다.
가장 최근 위치(마지막 사용자 메시지 끝)에 짧은 안내를 붙여 이를 막는다. 안내는 LLM 입력에만 들어가고 DB·화면에는 남지 않는다.
"""

SCOPE_REMINDER = (
    "\n\n[시스템 안내 — 사용자에게 보이지 않는 메모]\n"
    "- 위 메시지에 대해서만 응답하세요.\n"
    "- 위 메시지가 새로운 질문·요청이면(후속 질문, 다른 대상으로 바꾼 질문, '다시 조회해줘' 같은 명시적 재요청 포함) "
    "필요한 도구를 사용해 평소처럼 끝까지 처리하세요.\n"
    "- 이전 대화에서 이미 처리한 요청(조회·검색·분석·작업)은 끝난 일입니다. 위 메시지가 그것을 다시 요구하지 않는다면 "
    "다시 조회하거나 결과를 반복하지 마세요.\n"
    "- 질문·요청이 전혀 없는 서술(선호·사실·감상 공유 등)일 때만, 한두 문장으로 자연스럽게 반응하고 도구·팀원 위임·위젯은 사용하지 마세요."
)


def with_scope_reminder(user_input: str, has_history: bool) -> str:
    """이전 대화가 있을 때만 마지막 사용자 메시지 뒤에 범위 안내를 붙인다."""
    return user_input + SCOPE_REMINDER if has_history else user_input
